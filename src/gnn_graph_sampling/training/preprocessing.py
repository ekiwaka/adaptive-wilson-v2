from __future__ import annotations
import hashlib
import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Optional
import torch
from torch_geometric.data import Data
from torch_geometric.utils import k_hop_subgraph

from ..config.schema import SamplingConfig
from ..data.loading import DatasetBundle
from ..sampling.base import CenterSampler
from ..utils.io import ensure_dir, slugify


@dataclass(slots=True)
class ReducedGraphBundle:
    """Reduced training graph obtained by one preprocessing-time sampling event."""

    dataset: DatasetBundle
    center_original_ids: torch.Tensor
    original_node_ids: torch.Tensor
    metadata: dict[str, Any]
    cache_path: Optional[str] = None



def _load_trusted_cache(path: Path):
    """Load locally generated cache files across PyTorch versions.

    PyTorch 2.6 changed torch.load default to weights_only=True, which breaks
    caches containing custom Python objects. These cache files are generated by
    this project locally, so we load them with weights_only=False.
    """
    try:
        return torch.load(path, map_location='cpu', weights_only=False)
    except TypeError:
        # Older PyTorch versions do not support the weights_only argument.
        return torch.load(path, map_location='cpu')

def resolve_budget_count(sampling: SamplingConfig, num_candidate_nodes: int) -> int:
    """Resolve the configured budget into a concrete number of center nodes."""

    if num_candidate_nodes <= 0:
        raise ValueError('num_candidate_nodes must be positive.')

    raw_value: float
    if sampling.budget_value is not None:
        raw_value = float(sampling.budget_value)
        if sampling.budget_unit == 'count':
            budget = int(round(raw_value))
        else:
            budget = int(round(float(num_candidate_nodes) * raw_value))
    else:
        raw_value = float(sampling.batch_size)
        budget = int(sampling.batch_size)

    return max(1, min(int(budget), int(num_candidate_nodes)))



def _cache_key(dataset: DatasetBundle, sampling: SamplingConfig, *, seed: int, budget_count: int) -> str:
    payload = {
        'dataset_name': dataset.name,
        'dataset_kind': dataset.kind,
        'num_nodes': int(dataset.data.num_nodes),
        'num_edges': int(dataset.data.edge_index.size(1)),
        'feature_mode': dataset.metadata.get('feature_mode', 'unknown'),
        'sampler_name': sampling.name,
        'budget_unit': sampling.budget_unit,
        'budget_value': sampling.budget_value,
        'resolved_budget': int(budget_count),
        'num_hops': int(sampling.num_hops),
        'seed': int(seed),
        'wilson_q': float(sampling.wilson.q) if sampling.wilson.q is not None else None,
        'wilson_backend': sampling.wilson.backend,
    }
    digest = hashlib.sha1(json.dumps(payload, sort_keys=True).encode('utf-8')).hexdigest()
    return digest



def _build_reduced_dataset(
    dataset: DatasetBundle,
    center_nodes: torch.Tensor,
    metadata: dict[str, float],
    *,
    num_hops: int,
) -> ReducedGraphBundle:
    subset, sub_edge_index, mapping, _ = k_hop_subgraph(
        node_idx=center_nodes,
        num_hops=int(num_hops),
        edge_index=dataset.data.edge_index,
        relabel_nodes=True,
        num_nodes=int(dataset.data.num_nodes),
    )

    subset_cpu = subset.detach().cpu().to(torch.long)
    mapping_cpu = mapping.detach().cpu().to(torch.long)
    reduced_data = Data(
        x=dataset.data.x[subset_cpu].detach().cpu(),
        y=dataset.data.y[subset_cpu].detach().cpu(),
        edge_index=sub_edge_index.detach().cpu(),
        num_nodes=int(subset_cpu.numel()),
    )

    global_to_local = torch.full((int(dataset.data.num_nodes),), -1, dtype=torch.long)
    global_to_local[subset_cpu] = torch.arange(subset_cpu.numel(), dtype=torch.long)

    val_nodes = global_to_local[dataset.val_nodes.detach().cpu().to(torch.long)]
    val_nodes = val_nodes[val_nodes >= 0]
    test_nodes = global_to_local[dataset.test_nodes.detach().cpu().to(torch.long)]
    test_nodes = test_nodes[test_nodes >= 0]

    reduced_metadata = dict(dataset.metadata)
    reduced_metadata.update(
        {
            'is_preprocessed_graph': True,
            'original_num_nodes': int(dataset.data.num_nodes),
            'original_num_edges': int(dataset.data.edge_index.size(1)),
            'reduced_num_nodes': int(subset_cpu.numel()),
            'reduced_num_edges': int(sub_edge_index.size(1)),
            'resolved_budget': int(center_nodes.numel()),
            'center_fraction_of_reduced_graph': float(center_nodes.numel()) / max(int(subset_cpu.numel()), 1),
            **{str(key): float(value) for key, value in metadata.items()},
        }
    )

    reduced_bundle = DatasetBundle(
        name=dataset.name,
        kind=dataset.kind,
        data=reduced_data,
        num_features=int(reduced_data.x.size(-1)),
        num_classes=int(dataset.num_classes),
        train_nodes=mapping_cpu,
        val_nodes=val_nodes,
        test_nodes=test_nodes,
        metadata=reduced_metadata,
    )
    return ReducedGraphBundle(
        dataset=reduced_bundle,
        center_original_ids=center_nodes.detach().cpu().to(torch.long),
        original_node_ids=subset_cpu,
        metadata=reduced_metadata,
    )



def _build_full_graph_bundle(dataset: DatasetBundle) -> ReducedGraphBundle:
    full_metadata = dict(dataset.metadata)
    full_metadata.update(
        {
            'is_preprocessed_graph': True,
            'is_full_graph_baseline': True,
            'original_num_nodes': int(dataset.data.num_nodes),
            'original_num_edges': int(dataset.data.edge_index.size(1)),
            'reduced_num_nodes': int(dataset.data.num_nodes),
            'reduced_num_edges': int(dataset.data.edge_index.size(1)),
            'resolved_budget': int(dataset.train_nodes.numel()),
            'center_fraction_of_reduced_graph': float(dataset.train_nodes.numel()) / max(int(dataset.data.num_nodes), 1),
        }
    )
    return ReducedGraphBundle(
        dataset=dataset,
        center_original_ids=dataset.train_nodes.detach().cpu().to(torch.long),
        original_node_ids=torch.arange(int(dataset.data.num_nodes), dtype=torch.long),
        metadata=full_metadata,
    )


def prepare_reduced_graph(
    dataset: DatasetBundle,
    sampler: CenterSampler,
    sampling: SamplingConfig,
    generator: torch.Generator,
    *,
    seed: int,
    cache_root: Optional[Path] = None,
    force_cache: bool = False,
) -> ReducedGraphBundle:
    """Sample one reduced graph once, optionally using a reusable on-disk cache."""

    if sampling.name == 'none':
        return _build_full_graph_bundle(dataset)

    budget_count = resolve_budget_count(sampling, int(dataset.train_nodes.numel()))

    cache_path: Optional[Path] = None
    if cache_root is not None and (sampling.cache_preprocessed_graph or force_cache):
        cache_dir = ensure_dir(cache_root / sampling.cache_dirname / slugify(dataset.name))
        cache_path = cache_dir / f'{_cache_key(dataset, sampling, seed=seed, budget_count=budget_count)}.pt'
        if sampling.reuse_cached_preprocessed_graph and cache_path.exists():
            # payload = torch.load(cache_path, map_location='cpu')
            payload = _load_trusted_cache(cache_path)
            reduced_bundle = ReducedGraphBundle(
                dataset=payload['dataset'],
                center_original_ids=payload['center_original_ids'],
                original_node_ids=payload['original_node_ids'],
                metadata=payload['metadata'],
                cache_path=str(cache_path),
            )
            return reduced_bundle

    sample_out = sampler.sample(dataset.train_nodes, budget_count, generator=generator)
    reduced = _build_reduced_dataset(
        dataset,
        sample_out.center_nodes,
        sample_out.metadata,
        num_hops=int(sampling.num_hops),
    )

    if cache_path is not None:
        payload = {
            'dataset': reduced.dataset,
            'center_original_ids': reduced.center_original_ids,
            'original_node_ids': reduced.original_node_ids,
            'metadata': reduced.metadata,
        }
        torch.save(payload, cache_path)
        reduced.cache_path = str(cache_path)

    return reduced
